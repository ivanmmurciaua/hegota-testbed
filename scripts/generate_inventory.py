#!/usr/bin/env python3
"""Derive INVENTORY.md from the code, never hand-written.

Scans backends/ and core/pocs/ and emits an inventory of what exists: which backends
(network, verifier scheme) and which PoCs (EIPs asserted, artifacts, one-line claim).
The engine under core/vendor/ is third party and deliberately NOT inventoried.

Rules (repo-router discipline):
  - Denominator rule: if the corpus is empty, exit 1 ("NO PUDE MEDIR"), never a silent 0.
  - --check: regenerate in memory and compare with INVENTORY.md on disk; exit 1 if drift.

Usage:
  python scripts/generate_inventory.py            # write INVENTORY.md
  python scripts/generate_inventory.py --check     # fail if INVENTORY.md is stale
"""
import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
BACKENDS = os.path.join(REPO, "backends")
POCS = os.path.join(REPO, "core", "pocs")
OUT = os.path.join(REPO, "INVENTORY.md")
HEADER = "<!-- AUTO-GENERATED by scripts/generate_inventory.py. DO NOT EDIT. -->"

EIP_RE = re.compile(r"EIP-?\s?(\d{3,4})")
NUM_RE = re.compile(r"\b(8141|8250|8272|8288|8182|8312|7805)\b")
BIN_RE = re.compile(r"([A-Za-z0-9_]+\.bin)")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def scan_backends():
    rows = []
    if not os.path.isdir(BACKENDS):
        return rows
    for name in sorted(os.listdir(BACKENDS)):
        env = os.path.join(BACKENDS, name, "env")
        if not os.path.isfile(env):
            continue
        cfg = {}
        for line in read(env).splitlines():
            m = re.match(r"\s*export\s+([A-Z_]+)=(.*)", line)
            if m:
                cfg[m.group(1)] = m.group(2).strip()
        singleton = cfg.get("PQ_SINGLETON", "").strip()
        rows.append({
            "backend": name,
            "chain": cfg.get("PQ_CHAIN_ID", "?"),
            "rpc": cfg.get("PQ_RPC_URL", "?"),
            "verifier": singleton if singleton else "(none set: non-ML-DSA / aggregated)",
        })
    return rows


def scan_pocs():
    rows = []
    if not os.path.isdir(POCS):
        return rows
    for fn in sorted(os.listdir(POCS)):
        if not (fn.startswith("poc_") and fn.endswith(".py")):
            continue
        src = read(os.path.join(POCS, fn))
        doc = ast.get_docstring(ast.parse(src)) or ""
        claim = doc.strip().splitlines()[0].strip() if doc.strip() else "(no docstring)"
        eips = sorted({m for m in EIP_RE.findall(src)} | {m for m in NUM_RE.findall(src)}, key=int)
        arts = sorted(set(BIN_RE.findall(src)))
        rows.append({
            "poc": fn,
            "eips": ", ".join(eips) if eips else "-",
            "claim": claim,
            "artifacts": ", ".join(arts) if arts else "-",
        })
    return rows


def render(backends, pocs):
    lines = [HEADER, "", "# Inventory", "",
             "Generated from the code. Run `python scripts/generate_inventory.py` to refresh.",
             "The engine under `core/vendor/` is third party and not inventoried here.", "",
             "## Backends", "",
             "| backend | chainId | rpc | ML-DSA verifier |",
             "| --- | --- | --- | --- |"]
    for b in backends:
        lines.append(f"| {b['backend']} | {b['chain']} | {b['rpc']} | {b['verifier']} |")
    lines += ["", "## PoCs (core/pocs)", "",
              "| poc | EIPs | asserts | artifacts |",
              "| --- | --- | --- | --- |"]
    for p in pocs:
        claim = p["claim"].replace("|", "/")
        lines.append(f"| {p['poc']} | {p['eips']} | {claim} | {p['artifacts']} |")
    lines.append("")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    backends = scan_backends()
    pocs = scan_pocs()

    # denominator rule: an empty corpus is a measurement failure, never a quiet 0
    if not backends:
        sys.exit("NO PUDE MEDIR: no backends found under backends/")
    if not pocs:
        sys.exit("NO PUDE MEDIR: no PoCs found under core/pocs/")

    content = render(backends, pocs)

    if check:
        current = read(OUT) if os.path.isfile(OUT) else ""
        if current.rstrip("\n") != content.rstrip("\n"):
            sys.exit("INVENTORY.md is stale. Run: python scripts/generate_inventory.py")
        print(f"INVENTORY.md up to date ({len(backends)} backends, {len(pocs)} PoCs)")
        return

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(content + "\n")
    print(f"wrote INVENTORY.md ({len(backends)} backends, {len(pocs)} PoCs)")


if __name__ == "__main__":
    main()
